#!/usr/bin/env python3
"""Deterministic, lossless Lean projection of retained quadruple-construction data.

External JSON conversion, NOT a formally verified JSON parser. The --check mode
will compare projected literal blocks and pinned authoritative input bytes.
No acquisition, solver, Git, CVKT or publication operation is performed.
"""
from pathlib import Path
import argparse
import hashlib
import json
from itertools import product, combinations
from math import comb

ROOT = Path(__file__).resolve().parents[1]
ASSESS = ROOT/'research/cv43-seed-assessment-2026-10-22'
PILOT = ROOT/'research/c3743-construction-2026-10-22'
CONSTRUCT = ROOT/'research/cv43-constructions-2026-10-22'
OUT = ROOT/'lean/CoveringDesigns/QuadrupleAssembly/SeedData'


def input_file(path):
    """Resolve retained source identifiers through the package's pinned manifest.

    A publication can relocate inputs without changing any generated Lean bytes:
    source comments keep their historical identifiers, while every read uses the
    explicitly selected local file. There is no fallback to another repository.
    """
    manifest = json.loads((ROOT/'coverings/12u-plus-1-4-3/inputs.json').read_text())
    identifier = str(path.relative_to(ROOT))
    relative = manifest.get('input_locations', {}).get(identifier, identifier)
    if relative not in {item['path'] for item in manifest['inputs']}:
        raise ValueError(f'Unpinned quadruple input: {relative}')
    candidate = ROOT/relative
    if not candidate.resolve().is_relative_to(ROOT.resolve()):
        raise ValueError(f'Quadruple input escapes this package: {relative}')
    return candidate


def rows_literal(rows):
    return '[\n' + ',\n'.join('  {'+','.join(map(str,row))+'}' for row in rows) + '\n]'


def tree_literal(values):
    if len(set(values))==1:
        return f'.leaf {values[0]}'
    if len(values)%2:
        values=values+[0]
    return '(.fork ('+tree_literal(values[::2])+') ('+tree_literal(values[1::2])+'))'


# Retain the historical account identifier in generated provenance comments.
# Renaming the reader account must not change existing Lean projection bytes.
# Active input reads use the renamed manifest above.
def base_source(name, n, rows, source, g, k, t, mixed=False, cover=False):
    credit = 'Retained construction data; provenance and reuse terms: coverings/quadruple-assembly/sources.md.'
    if source and ('sqs-10' in str(source) or 'sqs-14' in str(source) or '4gdd-3-8' in str(source) or 'gdd-2-4' in str(source) or 'gdd-2-6' in str(source) or 'gdd-4-4' in str(source) or 'c13-ljcr' in str(source)):
        credit += '\nLJCR-derived data: Daniel M. Gordon / La Jolla Covering Repository, CC BY 4.0.'
    origin = str(source.relative_to(ROOT)) if source else ('Binary coordinate-sum formula, eight rows.' if name=='H4Two' else 'Coordinate-sum Latin square over Z6, 36 rows.')
    sha = hashlib.sha256(input_file(source).read_bytes()).hexdigest() if source else None
    table=[0]*comb(n,t)
    owners={}
    for i,row in enumerate(rows):
        for sub in combinations(sorted(row),t):
            key=sum(comb(x,j+1) for j,x in enumerate(sub))
            if key in owners and not cover:
                raise ValueError(f'duplicate incidence in {name}: {sub}')
            owners.setdefault(key,i)
    for key,i in owners.items():
        table[key]=i
    lines = ['import CoveringDesigns.QuadrupleAssembly.IndexedChecks',
             'import CoveringDesigns.QuadrupleAssembly.Transport',
             f'/-! Generated by scripts/quadruple_data.py.\n{credit}\nSource: {origin}\nSHA256: {sha}\n-/\n',
             'set_option Elab.async false', 'set_option maxRecDepth 50000',
             'set_option maxHeartbeats 10000000',
             f'namespace CoveringDesigns.QuadrupleAssembly.SeedData.{name}',
             'attribute [local instance 2000] Finset.decidableDforallFinset',
             f'def rows : List (Finset (Fin {n})) := '+rows_literal(rows),
             f'def blocks : Family (Fin {n}) := rows.toFinset',
             'def owners : IndexTree := '+tree_literal(table),
             f'def ownerIndex (T : Finset (Fin {n})) : Fin rows.length :=\n  ⟨owners.get (subsetCode {t} T) % rows.length, Nat.mod_lt _ (by decide +kernel)⟩']
    if cover:
        lines += [f'theorem checked : selectorCoverCheck id {t} rows ownerIndex = true := by decide +kernel',
                  f'theorem uniform_checked : rows.all (fun B => decide (B.card = {k})) = true := by decide +kernel',
                  f'theorem valid : IsCover blocks {k} {t} := selectorCoverCheck_sound {k} {t} rows ownerIndex uniform_checked checked',
                  f'theorem size : blocks.card = {len(rows)} := by decide +kernel']
    elif mixed:
        lines += [f'theorem checked : selectorMasterCheck ({g}) {t} rows ownerIndex = true := by decide +kernel',
                  f'theorem valid : Master ({g}) {t} blocks := selectorMasterCheck_sound ({g}) {t} rows ownerIndex checked',
                  'theorem sizes : ∀ B ∈ blocks, B.card = 4 ∨ B.card = 6 := by decide +kernel']
    else:
        lines += [f'theorem checked : selectorDesignCheck ({g}) {k} {t} rows ownerIndex = true := by decide +kernel',
                  f'theorem valid : GroupDesign ({g}) {k} {t} blocks := selectorDesignCheck_sound ({g}) {k} {t} rows ownerIndex checked']
    lines += [f'end CoveringDesigns.QuadrupleAssembly.SeedData.{name}']
    return '\n\n'.join(lines)+'\n'


def split_base(name,n,rows,source,g,k,t):
    full=base_source(name,n,rows,source,g,k,t)
    data=full[:full.index('theorem checked')]
    start=data.index('def rows :')
    end=data.index('def blocks :',start)
    pieces=[rows[i:i+32] for i in range(0,len(rows),32)]
    declarations=[f'def part{i} : List (Finset (Fin {n})) := '+rows_literal(r) for i,r in enumerate(pieces)]
    declarations.append(f'def rows : List (Finset (Fin {n})) := '+' ++ '.join(f'part{i}' for i in range(len(pieces))))
    data=data[:start]+'\n\n'.join(declarations)+'\n\n'+data[end:]
    ns=f'CoveringDesigns.QuadrupleAssembly.SeedData.{name}'
    data+=f'theorem uniform_checked : rows.all (fun B => decide (B.card = {k})) = true := by decide +kernel\n'
    data+=f'theorem transverse_checked : rows.all (fun B => decide ((B.image ({g})).card = B.card)) = true := by decide +kernel\n'
    data+=f'end {ns}\n'
    outputs={OUT/name/'Data.lean':data}
    modules=[]
    def pre(module):
        return f'import {ns}.Data\nset_option Elab.async false\nset_option maxRecDepth 50000\nset_option maxHeartbeats 10000000\nnamespace {ns}\n'
    for j in range(0,n,4):
        module=f'Forward{j//4}'
        text=pre(module)
        for i in range(j,min(j+4,n)):
            text+=f'theorem forward{i} : selectorCoverAt ({g}) {t} rows ownerIndex {i} = true := by decide +kernel\n'
        outputs[OUT/name/f'{module}.lean']=text+f'end {ns}\n'
        modules.append(module)
    for j in range(0,len(pieces),2):
        module=f'Reverse{j//2}'
        text=pre(module)
        for i in range(j,min(j+2,len(pieces))):
            text+=f'theorem reverse{i} : selectorInverseCheck {t} rows ownerIndex part{i} = true := by decide +kernel\n'
        outputs[OUT/name/f'{module}.lean']=text+f'end {ns}\n'
        modules.append(module)
    text='\n'.join(f'import {ns}.{m}' for m in modules)+'\nimport Mathlib.Tactic.FinCases\n'
    text+=f'namespace {ns}\n'
    text+=f'theorem checked : selectorDesignCheck ({g}) {k} {t} rows ownerIndex = true := by\n'
    text+=f'  have hc : selectorCoverCheck ({g}) {t} rows ownerIndex = true := by\n'
    text+=f'    apply selectorCoverCheck_of_slices ({g}) {t} rows ownerIndex (by decide)\n'
    text+='    intro a\n    fin_cases a\n'
    text+=''.join(f'    · exact forward{i}\n' for i in range(n))
    text+=f'  have hr : selectorInverseCheck {t} rows ownerIndex rows = true := by\n'
    text+='    change ('+' ++ '.join(f'part{i}' for i in range(len(pieces)))+').all _ = true\n'
    if len(pieces)>1:
        text+='    simp only [List.all_append, Bool.and_eq_true]\n'
    proof='reverse0'
    for i in range(1,len(pieces)):
        proof=f'⟨{proof},reverse{i}⟩'
    text+=f'    exact {proof}\n'
    text+=f'  have hm := selectorMasterCheck_of_parts ({g}) {t} rows ownerIndex transverse_checked hc hr\n'
    text+='  simpa only [selectorDesignCheck,uniform_checked,Bool.true_and] using hm\n'
    text+=f'theorem valid : GroupDesign ({g}) {k} {t} blocks := selectorDesignCheck_sound ({g}) {k} {t} rows ownerIndex checked\nend {ns}\n'
    outputs[OUT/f'{name}.lean']=text
    combined=data.replace(f'end {ns}\n','')
    combined=combined.replace('import CoveringDesigns.QuadrupleAssembly.IndexedChecks',
        'import CoveringDesigns.QuadrupleAssembly.IndexedChecks\nimport Mathlib.Tactic.FinCases')
    for module in modules:
        body=outputs[OUT/name/f'{module}.lean'].split(f'namespace {ns}\n',1)[1]
        combined+=body.replace(f'end {ns}\n','')
    combined+=text.split(f'namespace {ns}\n',1)[1]
    return {OUT/f'{name}.lean':combined}



def generate_bases():
    specs=[]
    for n in [8,10,12,14,16]:
        path=ASSESS/('bases/twb-12.json' if n==12 else (f'inputs/sqs-{n}.json' if n in [10,14] else f'bases/sqs-{n}.json'))
        specs.append((f'Master{n}',n,path,'id',4,3,n==12,False))
    specs += [('Hanani',18,PILOT/'seeds/h6-3-hanani.json','fun x : Fin 18 => x.val / 3',4,3,False,False),
              ('H4Six',24,ASSESS/'bases/h-4-6.json','fun x : Fin 24 => x.val / 6',4,3,False,False)]
    for u in [4,6,7]:
        specs.append((f'GDD2_{u}',2*u,ASSESS/f'bases/gdd-2-{u}.json',f'fun x : Fin {2*u} => x.val / 2',3,2,False,False))
    specs.append(('GDD4_4',16,ASSESS/'bases/gdd-4-4.json','fun x : Fin 16 => x.val / 4',3,2,False,False))
    for u in [5,8]:
        specs.append((f'FourGDD3_{u}',3*u,ASSESS/f'bases/4gdd-3-{u}.json',f'fun x : Fin {3*u} => x.val / 3',4,2,False,False))
    specs.append(('PilotGDD',36,CONSTRUCT/'gdd-12-3-calibration.json','fun x : Fin 36 => x.val / 12',3,2,False,False))
    specs.append(('Filling',13,PILOT/'seeds/c13-ljcr.json','id',4,3,False,True))
    outputs={}
    for name,n,path,g,k,t,mixed,cover in specs:
        rows=json.loads(input_file(path).read_text())['blocks']
        if any(len(set(row)) != len(row) or any(type(x) is not int or not 0<=x<n for x in row) for row in rows):
            raise ValueError(f'invalid input rows: {path}')
        if not mixed and not cover:
            outputs.update(split_base(name,n,rows,path,g,k,t))
        else:
            outputs[OUT/f'{name}.lean']=base_source(name,n,rows,path,g,k,t,mixed,cover)
    rows=[[a,2+b,4+c,6+((a+b+c)%2)] for a,b,c in product(range(2),repeat=3)]
    outputs.update(split_base('H4Two',8,rows,None,'fun x : Fin 8 => x.val / 2',4,3))
    rows=[[a,6+b,12+((-a-b)%6)] for a,b in product(range(6),repeat=2)]
    outputs.update(split_base('LatinSix',18,rows,None,'fun x : Fin 18 => x.val / 6',3,2))
    return outputs


def generate_small_cover():
    """The retained 25-point cover, using the existing checked selector interface.

    Small row chunks and least-point slices bound kernel reduction; the
    selector remains untrusted data until each slice is checked in Lean.
    Existing seed and six-witness projections are unaffected.
    """
    source = ROOT/'data/quadruple-assembly/blocks-25-4-3-600.json'
    rows = json.loads(input_file(source).read_text())['blocks']
    text = base_source('V25', 25, rows, source, 'id', 4, 3, cover=True)
    text = text.replace('SeedData.V25', 'WitnessData.V25')
    text = text.replace('import CoveringDesigns.QuadrupleAssembly.Transport',
                        'import CoveringDesigns.QuadrupleAssembly.Transport\nimport Mathlib.Tactic.FinCases')
    text = text.replace('Source: ', 'LJCR-derived data: Daniel M. Gordon / La Jolla Covering Repository, CC BY 4.0.\nSource: ', 1)
    pieces = [rows[i:i+32] for i in range(0, len(rows), 32)]
    declarations = [f'def part{i} : List (Finset (Fin 25)) := '+rows_literal(piece)
                    for i, piece in enumerate(pieces)]
    declarations.append('def rows : List (Finset (Fin 25)) := '+' ++ '.join(f'part{i}' for i in range(len(pieces))))
    start, end = text.index('def rows :'), text.index('def blocks :')
    text = text[:start]+'\n\n'.join(declarations)+'\n\n'+text[end:]
    ns = 'CoveringDesigns.QuadrupleAssembly.WitnessData.V25'
    data = text[:text.index('theorem checked')]
    data += 'theorem uniform_checked : rows.all (fun B => decide (B.card = 4)) = true := by decide +kernel\n'
    data += f'end {ns}\n'
    outputs = {OUT.parent/'WitnessData/V25/Data.lean': data}
    for i in range(25):
        proof = f'import {ns}.Data\nset_option Elab.async false\nset_option maxRecDepth 50000\nset_option maxHeartbeats 10000000\nnamespace {ns}\n'
        proof += f'theorem forward{i} : selectorCoverAt id 3 rows ownerIndex {i} = true := by decide +kernel\nend {ns}\n'
        outputs[OUT.parent/f'WitnessData/V25/Forward{i}.lean'] = proof
    joined = '\n'.join(f'import {ns}.Forward{i}' for i in range(25))+'\nimport Mathlib.Tactic.FinCases\nimport CoveringDesigns.Schoenheim.LowerBound\n'
    joined += f'namespace {ns}\n'
    joined += ('theorem checked : selectorCoverCheck id 3 rows ownerIndex = true := by\n'
               '  apply selectorCoverCheck_of_slices id 3 rows ownerIndex (by decide)\n'
               '  intro a\n  fin_cases a\n'+''.join(f'  · exact forward{i}\n' for i in range(25)))
    joined += 'theorem valid : IsCover blocks 4 3 := selectorCoverCheck_sound 4 3 rows ownerIndex uniform_checked checked\n'
    joined += ('theorem size : blocks.card = 600 := by\n'
               '  have hu : blocks.card ≤ 600 := (List.toFinset_card_le rows).trans_eq (by decide +kernel)\n'
               '  have hl := Schoenheim.lower_bound (by decide : 1 ≤ 3) (by decide : 3 ≤ 4)\n'
               '    (by decide : 4 ≤ Fintype.card (Fin 25)) valid\n'
               '  have he : Schoenheim.bound 25 4 3 = 600 := by decide +kernel\n'
               '  rw [Fintype.card_fin, he] at hl\n'
               '  exact Nat.le_antisymm hu hl\n')
    joined += f'end {ns}\n'
    outputs[OUT.parent/'WitnessData/V25.lean'] = joined
    return outputs


def witness_source(u):
    v,b=12*u+1,6*u*u*(12*u+1)
    return PILOT/'blocks-37-4-3-1998.json' if u==3 else CONSTRUCT/f'witnesses/blocks-{v}-4-3-{b}.json'


def read_rows(path):
    return json.loads(input_file(path).read_text())['blocks']


def witness_pieces(u):
    """Reorder actual authoritative rows by the structural map; never fabricate data."""
    source=witness_source(u)
    rows=read_rows(source)
    actual={tuple(sorted(b)):b for b in rows}
    if len(actual)!=len(rows):
        raise ValueError('duplicate distributed row')
    pieces=[]
    def add(kind,expr,candidates):
        projected=[actual.pop(tuple(sorted(row))) for row in candidates]
        pieces.append((kind,expr,projected))
    binary=[[a,2+b,4+c,6+((a+b+c)%2)] for a,b,c in product(range(2),repeat=3)]
    hanani=read_rows(PILOT/'seeds/h6-3-hanani.json')
    h6=[[2*sorted(B)[x//2]+x%2 for x in D] for B in hanani for D in binary]
    h4=read_rows(ASSESS/'bases/h-4-6.json')
    block=lambda B:'{'+','.join(map(str,B))+'}'
    if u==3:
        for B in hanani:
            add('A','hPilotPiece '+block(B),[[2*sorted(B)[x//2]+x%2 for x in D] for D in binary])
    else:
        path=ASSESS/('bases/twb-12.json' if u==6 else f'inputs/sqs-{2*u}.json' if u in [5,7] else f'bases/sqs-{2*u}.json')
        for B in read_rows(path):
            add('A',f'hPiece (u := {u}) '+block(B),[[6*sorted(B)[x//6]+x%6 for x in D] for D in (h4 if len(B)==4 else h6)])
    if u==3:
        for B in read_rows(CONSTRUCT/'gdd-12-3-calibration.json'):
            add('B','[gPilotPiece '+block(B)+']',[B+[36]])
    else:
        latin=u in [4,6,7]
        path=ASSESS/f'bases/gdd-2-{u}.json' if latin else ASSESS/f'bases/4gdd-3-{u}.json'
        template=[[a,6+b,12+((-a-b)%6)] for a,b in product(range(6),repeat=2)] if latin else read_rows(ASSESS/'bases/gdd-4-4.json')
        w=6 if latin else 4
        for B in read_rows(path):
            add('B',f'g{"Latin" if latin else "Four"}Piece (u := {u}) '+block(B),
                [[w*sorted(B)[x//w]+x%w for x in D]+[12*u] for D in template])
    for h in range(u):
        add('C',f'cPiece (u := {u}) {h}',[[12*u if x==12 else 12*h+x for x in B] for B in read_rows(PILOT/'seeds/c13-ljcr.json')])
    factors=json.loads(input_file(ASSESS/'bases/factors-6.json').read_text())['factors']
    for h,k in combinations(range(u),2):
        for a,b in product(range(2),repeat=2):
            add('D',f'labelledDPiece (u := {u}) {h} {k} {a} {b}',
                [[12*h+6*a+x for x in E]+[12*k+6*b+x for x in D] for F in factors for E,D in product(F,repeat=2)])
    if actual:
        raise ValueError(f'Unprojected actual blocks for u={u}: {len(actual)}')
    return pieces


def generate_witnesses(orders):
    outputs={}
    for u in orders:
        v=12*u+1
        ns=f'CoveringDesigns.QuadrupleAssembly.WitnessData.V{v}'
        pieces=witness_pieces(u)
        # Small compilation units and separate equality proofs bound kernel reduction.
        batches=[]
        batch=[]
        size=0
        for i,(kind,expr,rows) in enumerate(pieces):
            if batch and size+len(rows)>900:
                batches.append(batch); batch=[];size=0
            batch.append((i,kind,expr,rows));size+=len(rows)
        if batch:batches.append(batch)
        for j,batch in enumerate(batches):
            lines=['import CoveringDesigns.QuadrupleAssembly.AssemblyRows',
                   '/-! Lossless projection of actual distributed blocks; external JSON conversion.\n'
                   f'Source: {witness_source(u).relative_to(ROOT)}\n'
                   f'SHA256: {hashlib.sha256(input_file(witness_source(u)).read_bytes()).hexdigest()}\n'
                   'Provenance, including LJCR-derived filling and seeds: coverings/quadruple-assembly/sources.md. -/',
                   'set_option Elab.async false','set_option maxRecDepth 50000','set_option maxHeartbeats 10000000',
                   f'namespace {ns}']
            for i,kind,expr,rows in batch:
                lines += [f'def piece{i} : List (Finset (Fin {v})) := '+rows_literal(rows),
                          f'theorem piece{i}_eq : piece{i} = {expr} := by decide +kernel']
            lines += [f'end {ns}']
            outputs[OUT.parent/f'WitnessData/V{v}/Part{j}.lean']='\n\n'.join(lines)+'\n'
        lines=[*(f'import {ns}.Part{j}' for j in range(len(batches))),
               'set_option Elab.async false','set_option linter.unusedSimpArgs false',
               'set_option maxRecDepth 50000','set_option maxHeartbeats 10000000',
               f'namespace {ns}', 'open SeedData']
        simplify=['List.flatMap_cons','List.flatMap_nil','List.flatten_cons','List.flatten_nil',
                  'List.map_cons','List.map_nil','List.map_append','List.nil_append','List.append_nil','List.singleton_append','List.cons_append','List.append_assoc']
        for kind in 'ABCD':
            indices=[i for i,p in enumerate(pieces) if p[0]==kind]
            lines.append(f'def file{kind} : List (Finset (Fin {v})) := ['+', '.join(f'piece{i}' for i in indices)+'].flatten')
            lines.append(f'theorem file{kind}_eq : file{kind} = transportRows (labelEquiv {u}) ({kind.lower()}Rows {u}) := by')
            if kind=='A':
                name='Hanani' if u==3 else f'Master{2*u}'
                if u==3:
                    lines.append('  rw [labelled_hPilot]')
                else:
                    lines.append(f'  change fileA = transportRows (labelEquiv {u}) ((hFromRows (u := {u}) {name}.rows).map _)')
                    lines.append('  rw [labelled_hFrom]')
                aux=[f'{name}.rows']+[f'{name}.part{i}' for i in range((len(read_rows(PILOT/'seeds/h6-3-hanani.json' if u==3 else ASSESS/('bases/twb-12.json' if u==6 else f'inputs/sqs-{2*u}.json' if u in [5,7] else f'bases/sqs-{2*u}.json')))+31)//32)] if u!=6 else ['Master12.rows']
            elif kind=='B':
                name='PilotGDD' if u==3 else f'GDD2_{u}' if u in [4,6,7] else f'FourGDD3_{u}'
                if u==3:
                    lines.append('  rw [labelled_gPilot]')
                else:
                    method='Latin' if u in [4,6,7] else 'Four'
                    lines.append(f'  change fileB = transportRows (labelEquiv {u}) ((g{method}Rows (u := {u}) {name}.rows).map _)')
                    lines.append(f'  rw [labelled_g{method}]')
                count=len(indices)
                aux=[f'{name}.rows']+[f'{name}.part{i}' for i in range((count+31)//32)]
            elif kind=='C':
                lines.append('  rw [labelled_cRows]')
                lines.append(f'  have hr : List.finRange {u} = ['+','.join(map(str,range(u)))+'] := by decide +kernel')
                aux=['hr']
            else:
                lines.append('  rw [labelled_dIndices]')
                dlist=[f'({h},{k},{a},{b})' for h,k in combinations(range(u),2) for a,b in product(range(2),repeat=2)]
                lines.append(f'  have hr : dIndices {u} = ['+','.join(dlist)+'] := by decide +kernel')
                aux=['hr']
            rules=[f'file{kind}',*(f'piece{i}_eq' for i in indices),*aux,'List.flatMap_append',*simplify]
            lines.append('  simp only ['+', '.join(rules)+']')
        lines += [f'def rows : List (Finset (Fin {v})) := fileA ++ fileB ++ fileC ++ fileD',
                  f'def blocks : Family (Fin {v}) := rows.toFinset',
                  f'theorem rows_eq : rows = labelledRows {u} := by\n  rw [rows,fileA_eq,fileB_eq,fileC_eq,fileD_eq,labelledRows_parts]',
                  f'theorem correspondence : blocks = labelledFamily {u} := congrArg List.toFinset rows_eq',
                  f'theorem optimal : IsCover blocks 4 3 ∧ blocks.card = {6*u*u*v} := by\n  rw [correspondence]\n  exact labelledFamily_optimal (by decide) (by decide)',
                  f'end {ns}']
        outputs[OUT.parent/f'WitnessData/V{v}.lean']='\n\n'.join(lines)+'\n'
    return outputs


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--witnesses',nargs='*',type=int,default=[3,4,5,6,7,8])
    args=parser.parse_args()
    outputs=generate_bases()
    outputs.update(generate_small_cover())
    outputs.update(generate_witnesses(args.witnesses))
    differences=[]
    for path,source in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text()!=source:
                differences.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            if not path.is_file() or path.read_text()!=source:
                path.write_text(source)
    print(json.dumps({'mode':'check' if args.check else 'projection','files':len(outputs),'differences':differences}))
    raise SystemExit(bool(differences))

