#!/usr/bin/env python3
"""Untrusted certificates for GPPT Figure 1 completion isomorphisms.

The first added pair is normalized to {4,5} or {4,8} by an explicit template
automorphism, leaving 1568 cases. Automorphisms are shared and checked once.
The generator does not search covering families or supply proof assumptions.
"""
import argparse
import gzip
import hashlib
from itertools import combinations
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def mask(points):
    return sum(1 << q for q in points)


def pack(values, width=4):
    return sum(value << (width*i) for i, value in enumerate(values))


def data():
    fig = json.loads((ROOT / "data/gppt-figure1.json").read_text())
    core = [frozenset(b) for b in fig["full_blocks"]]
    spines = [frozenset(b) for b in fig["short_blocks"]]
    choices = [list(combinations(sorted(set(range(12)) - s), 2)) for s in spines]
    raw = gzip.decompress((ROOT / "data/completion-isomorphisms.bin.gz").read_bytes())
    records = [(raw[i]-1, tuple(raw[i+1:i+13])) for i in range(0, len(raw), 13)]
    assert len(records) == 28**3
    permutations = sorted({p for _, p in records})
    normal_records = records[:28**2] + records[3*28**2:4*28**2]
    normalizers = []
    for pair in choices[0]:
        tag = pair[0] // 4 != pair[1] // 4
        target = frozenset((4, 8) if tag else (4, 5))
        permutation = next(p for p in permutations
                           if p[0] // 4 == 0 and frozenset(p[q] for q in pair) == target)
        normalizers.append((tag, permutation))
    selected = sorted({p for _, p in normal_records} | {p for _, p in normalizers})
    indices = {p: i for i, p in enumerate(selected)}
    auts = []
    for p in selected:
        assert sorted(p) == list(range(12))
        rows = [core.index(frozenset(p[q] for q in row)) for row in core]
        fibres = [spines.index(frozenset(p[q] for q in row)) for row in spines]
        auts.append((pack(p), pack(rows), pack(fibres, 2)))
    links = json.loads((ROOT / "data/links-68.json").read_text())["links"]
    target_pairs = []
    for link in links[:67]:
        extras = set(map(frozenset, link["blocks"])) - set(core)
        assert len(extras) == 3
        target_pairs.append([tuple(sorted(next(b for b in extras if s <= b)-s)) for s in spines])
    for flat, (class_id, p) in enumerate(normal_records):
        tag, rem = divmod(flat, 28**2)
        j, k = divmod(rem, 28)
        inputs = [(4, 8) if tag else (4, 5), choices[1][j], choices[2][k]]
        for i, pair in enumerate(inputs):
            target = target_pairs[class_id][p[4*i]//4]
            assert frozenset(p[q] for q in pair) == frozenset(target)
    return {
        "core_code": sum(1 << (12*q+r) for r, row in enumerate(core) for q in row),
        "automorphisms": auts,
        "choices": choices,
        "normalizers": [(tag, indices[p]) for tag, p in normalizers],
        "target_pairs": target_pairs,
        "completion_records": [(indices[p], c) for c, p in normal_records],
    }


def production_data(d):
    """Produce witness data only: Lean separately checks every property used."""
    def pair(p):
        return f"({p[0]}, {p[1]})"
    text = """import CoveringDesigns.C12_6_3.Structural.CompletionEncoding

/-! Generated by scripts/generate_gppt_completions.py --generate.
These are explicit witnesses, not axioms. The source binary is retained in
data/completion-isomorphisms.bin.gz; all facts used are checked in Lean.
-/

set_option exponentiation.threshold 1024
namespace CoveringDesigns.GPPTStructural.CompletionVerification

"""
    for i in range(4):
        text += f"def autChunk{i} : List AutCert := [\n  "
        text += ",\n  ".join(f"({p}#48, {r}#48, {f}#6)"
                              for p, r, f in d["automorphisms"][64*i:64*(i+1)]) + "\n]\n\n"
    text += """def autList : List AutCert := autChunk0 ++ autChunk1 ++ autChunk2 ++ autChunk3
theorem autList_length : autList.length = 256 := by decide +kernel
def autAt (i : Fin 256) : AutCert := autList[i.val]'(by rw [autList_length]; exact i.isLt)

def choiceData : Array (Array Pair) := #[
"""
    text += ",\n".join("  #[" + ", ".join(map(pair, row)) + "]" for row in d["choices"])
    text += """
]
def choice (i : Fin 3) (j : Fin 28) : Pair := (choiceData[i.val]!)[j.val]!

def targetData : Array (Array Pair) := #[
"""
    text += ",\n".join("  #[" + ", ".join(map(pair, row)) + "]" for row in d["target_pairs"])
    text += """
]
def targetPair (c : Fin 67) (i : Fin 3) : Pair := (targetData[c.val]!)[i.val]!

def normalizerData : Array (Bool × Fin 256) := #[
  """
    text += ",\n  ".join(f"({str(tag).lower()}, {i})" for tag, i in d["normalizers"])
    text += """
]
def normalizer (j : Fin 28) : Bool × Fin 256 := normalizerData[j.val]!

def normalPairs (x : NormalInput) : Fin 3 → Pair :=
  ![firstPair x.1, choice 1 x.2.1, choice 2 x.2.2]

def normalAdditions (x : NormalInput) : Fin 3 → Finset (Fin 12) :=
  fun i => pairSet (normalPairs x i)

def targetAdditions (c : Fin 67) : Fin 3 → Finset (Fin 12) :=
  fun i => pairSet (targetPair c i)

def normalizerCheck (j : Fin 28) : Bool :=
  let n := normalizer j
  let a := autAt n.2
  fibreMap a.2.2 0 == 0 && pairEq (mapPair (pointMap a.1) (choice 0 j)) (firstPair n.1)

def completionCheck (r : CompletionRow) : Bool :=
  let a := autAt r.2.1
  (List.finRange 3).all fun i => pairEq
    (mapPair (pointMap a.1) (normalPairs r.1 i))
    (targetPair r.2.2 (fibreMap a.2.2 i))

"""
    for ci in range(4):
        text += f"def completionChunk{ci} : List CompletionRow := [\n  "
        rows = []
        for idx in range(392*ci, 392*(ci+1)):
            aut, c = d["completion_records"][idx]
            tag, rem = divmod(idx, 28**2)
            j, k = divmod(rem, 28)
            rows.append(f"(({str(bool(tag)).lower()}, {j}, {k}), {aut}, {c})")
        text += ",\n  ".join(rows) + "\n]\n\n"
    text += """def completionRows : List CompletionRow :=
  completionChunk0 ++ completionChunk1 ++ completionChunk2 ++ completionChunk3

end CoveringDesigns.GPPTStructural.CompletionVerification
"""
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--generate", action="store_true", help="write the Lean witness data")
    mode.add_argument("--check", action="store_true", help="check reproducibility (the default)")
    args = parser.parse_args()
    d = data()
    text = production_data(d)
    out = ROOT / "lean/CoveringDesigns/C12_6_3/Structural/CompletionData.lean"
    if args.generate:
        out.write_text(text)
    elif not out.exists() or out.read_text() != text:
        raise SystemExit("CompletionData.lean does not match the deterministic generator")
    inputs = ["data/gppt-figure1.json", "data/links-68.json", "data/completion-isomorphisms.bin.gz"]
    print(json.dumps({
        "source": str(out.relative_to(ROOT)),
        "sha256": hashlib.sha256(text.encode()).hexdigest(),
        "automorphisms": len(d["automorphisms"]),
        "normalizers": len(d["normalizers"]),
        "normalized_completions": len(d["completion_records"]),
        "reproducible": True,
        "input_sha256": {name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest() for name in inputs}
    }, indent=2))


if __name__ == "__main__":
    main()
